from conftest import FIXTURE_INTAKE, install

USER_SETTINGS = {"model": "keep-me", "permissions": {"allow": ["Bash(ls *)"], "deny": ["Read(./secrets/**)"]},
                 "hooks": {"PreToolUse": [{"matcher": "Bash",
                                           "hooks": [{"type": "command", "command": "echo user-hook"}]}]}}


def settings(repo):
    return json.loads((repo / ".claude/settings.json").read_text())


def test_install_is_lint_clean(installed):
    """Phase 3 exit: rendered output passes lint (V7)."""
    fails, _ = lint.lint(installed)
    assert fails == []
    assert lint.main([str(installed)]) == 0


def test_r5_existing_settings_survive(tmp_path):
    """R5: merge, never overwrite; back up first; user keys and hooks kept."""
    repo = install(tmp_path / "r", settings=USER_SETTINGS)
    s = settings(repo)
    assert s["model"] == "keep-me"
    assert "Bash(ls *)" in s["permissions"]["allow"]
    assert "Read(./secrets/**)" in s["permissions"]["deny"]
    assert any(h["command"] == "echo user-hook" for g in s["hooks"]["PreToolUse"] for h in g["hooks"])
    assert json.loads((repo / render.BACKUP).read_text()) == USER_SETTINGS
    assert lint.lint(repo)[0] == []


def test_rerender_is_idempotent_and_keeps_first_backup(tmp_path):
    repo = install(tmp_path / "r", settings=USER_SETTINGS)
    first = settings(repo)
    render.render(repo)
    render.render(repo)
    assert settings(repo) == first
    assert json.loads((repo / render.BACKUP).read_text()) == USER_SETTINGS


def test_invalid_existing_settings_refused(tmp_path):
    repo = tmp_path / "r"
