def test_x2_disabled_rule_rendered_with_reason(installed):
    """X1 recorded with date and user; X2 renders 'disabled: <reason>' and drops enforcement."""
    reason = "Nightly backups run pg_dump from this repo by design."
    e = exceptions.add(installed, rule="P9-db-dump", reason=reason, today=D, user="sandhya@example.com")
    assert e == {"kind": "rule", "rule": "P9-db-dump", "reason": reason, "date": "2026-09-29",
                 "by": "sandhya@example.com"}
    render.render(installed)
    md = (installed / render.RULES_MD).read_text()
    assert f"- P9-db-dump: disabled: {reason}" in md
    assert "Bash(pg_dump *)" not in settings(installed)["permissions"].get("ask", [])
    cfg = json.loads((installed / ".claude/hooks/governor_config.json").read_text())
    assert not any(r["rule"] == "P9-db-dump" for r in cfg["bash_ask"])
    assert lint.lint(installed)[0] == []


