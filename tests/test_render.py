def test_settings_with_bom_is_accepted(tmp_path):
    repo = tmp_path / "r"
    (repo / ".claude").mkdir(parents=True)
    (repo / ".claude/settings.json").write_bytes(b"\xef\xbb\xbf" + json.dumps({"model": "m"}).encode())
