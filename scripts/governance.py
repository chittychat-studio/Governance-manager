"""governance.yaml: the single source of truth (SPEC R1, T6, X1-X4, P4).

Usage: python scripts/governance.py <repo> --intake intake.json [--mcp-allow a,b]
Writes <repo>/governance.yaml, keeping existing exceptions and mcp_allow.
"""
import argparse
import json
import os
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from intake import validate  # noqa: E402
from pyfind import default_python  # noqa: E402
from packs import PackError  # noqa: E402
from select_pack import select  # noqa: E402
from tier import compute_tier, load_tiers  # noqa: E402

GOVERNOR_VERSION = "0.1.0"
HEADER = "# Generated by Governor. Edit through scripts/governance.py and scripts/exceptions.py, then re-render.\n"
FILENAME = "governance.yaml"


def effective_tier(computed, exceptions):
    """Lowest tier granted by a tier exception, else the computed tier (T6, X4)."""
    lowered = [e["tier"] for e in exceptions if e.get("kind") == "tier"]
    return min([computed] + lowered)


def build(intake, exceptions=(), mcp_allow=(), hook_python=None):
    """Assemble the governance dict from intake + tier + packs + exceptions (R1)."""
    validate(intake)
    exceptions = list(exceptions)
    computed, matched = compute_tier(intake)
    eff = effective_tier(computed, exceptions)
    sel = select(intake, eff)
    return {
        "governor_version": GOVERNOR_VERSION,
        "intake": intake,
        "tier": {"computed": computed, "matched": matched, "effective": eff,
                 "tiers_version": load_tiers()["version"]},
        "packs": {agent: {"pack_id": s["pack_id"],
                          "pins": [{"id": pid, "sha256": h} for pid, h in s["pins"]]}
                  for agent, s in sel.items()},
        "mcp_allow": sorted(set(mcp_allow)),
        "hook_python": hook_python or default_python(),
        "exceptions": exceptions,
    }


def read(repo):
    """Load <repo>/governance.yaml, or None."""
    p = Path(repo) / FILENAME
    return yaml.safe_load(p.read_text(encoding="utf-8")) if p.exists() else None


def write(repo, gov):
    """Write <repo>/governance.yaml with the generated header (R1, R4)."""
    text = HEADER + yaml.safe_dump(gov, sort_keys=False, allow_unicode=True)
    (Path(repo) / FILENAME).write_text(text, encoding="utf-8")


def main(argv=None):
    """CLI (R1)."""
    ap = argparse.ArgumentParser()
    ap.add_argument("repo")
    ap.add_argument("--intake", required=True)
    ap.add_argument("--mcp-allow", default=None, help="comma-separated MCP server names")
    args = ap.parse_args(argv)
    intake = json.loads(Path(args.intake).read_text(encoding="utf-8"))
    old = read(args.repo) or {}
    mcp = args.mcp_allow.split(",") if args.mcp_allow is not None else old.get("mcp_allow", [])
    try:
        gov = build(intake, old.get("exceptions", []), [m.strip() for m in mcp if m.strip()],
                    old.get("hook_python"))
    except (PackError, ValueError) as exc:
        print(str(exc), file=sys.stderr)
        return 4
    write(args.repo, gov)
    print(f"governance.yaml written: tier {gov['tier']['effective']} "
          f"(computed {gov['tier']['computed']} via {gov['tier']['matched']})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
