"""Remove Governor from a repo, keeping everything that is the user's (SPEC U1, R5, X1). Stdlib only (E8).

Usage: python scripts/remove.py <repo>              # show what would be removed; changes nothing
       python scripts/remove.py <repo> --yes        # remove it (run this yourself; the agent is blocked, P9)
       python scripts/remove.py <repo> --yes --purge   # also delete governance.yaml (tier, exceptions)

Removed: Governor's own entries in .claude/settings.json (per .claude/.governor-managed.json), its hook files,
rules file, coverage and state, its marked blocks in CLAUDE.md / AGENTS.md, and CI files it wrote.
Kept: every settings entry, hook and line of text that is yours, the settings backup, and governance.yaml
unless --purge.
"""
import argparse
import json
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ci  # noqa: E402
import render  # noqa: E402

STATE_DIR = ".claude/governor"


def _without_block(text):
    """Text with Governor's marked block cut out, or None if there is no block."""
    if render.BLOCK_START not in text or render.BLOCK_END not in text:
        return None
    nl = "\r\n" if "\r\n" in text else "\n"   # keep the file's own line endings
    pre, rest = text.split(render.BLOCK_START, 1)
    after = rest.split(render.BLOCK_END, 1)[1]
    return (pre.rstrip("\r\n") + (nl if pre.strip() else "") + after.lstrip("\r\n")).rstrip("\r\n") + nl


def plan(repo, purge=False):
    """List of (action, path, detail). Nothing is changed."""
    repo = Path(repo).resolve()
    managed_p = repo / render.MANAGED
    managed = json.loads(managed_p.read_text(encoding="utf-8")) if managed_p.exists() else None
    acts = []
    settings = repo / ".claude" / "settings.json"
    if managed is not None and settings.exists():
        data = json.loads(settings.read_text(encoding="utf-8-sig"))
        perms = data.get("permissions", {})
        drop = {k: [e for e in perms.get(k, []) if e in set(managed.get(k, []))] for k in ("deny", "ask")}
        hooks = sum(1 for groups in data.get("hooks", {}).values() for g in groups
                    for h in g.get("hooks", []) if render.is_governor_hook(h))
        acts.append(("edit", settings, f"remove Governor's {len(drop['deny'])} deny, {len(drop['ask'])} ask "
                                       f"entries and {hooks} hook entries; your own entries stay"))
    for rel in (managed or {}).get("files", []):
        p = repo / rel
        if p.exists() and not rel.startswith(STATE_DIR + "/"):
            acts.append(("delete", p, "generated by Governor"))
    for name in ("CLAUDE.md", "AGENTS.md"):
        p = repo / name
        if p.exists():
            rest = _without_block(render.read_user_text(p))
            if rest is not None:
                empty = not rest.replace(render.CLAUDE_MD_HEADER, "").strip()
                acts.append(("delete" if empty else "unblock", p,
                             "only Governor's text was in it" if empty else "remove Governor's block; your text stays"))
    if (repo / STATE_DIR).exists():
        acts.append(("delete_dir", repo / STATE_DIR, "Governor's state, log and coverage"))
    if managed_p.exists():
        acts.append(("delete", managed_p, "Governor's ownership record"))
    if ci.owned(repo):
        acts.append(("delete_dir", repo / ".governor", "CI runtime written by Governor"))
        wf = repo / ci.WORKFLOW
        if wf.exists() and "Governor" in wf.read_text(encoding="utf-8", errors="ignore"):
            acts.append(("delete", wf, "CI workflow written by Governor"))
    gov = repo / "governance.yaml"
    if gov.exists():
        acts.append(("delete", gov, "--purge: tier, exceptions and answers") if purge else
                    ("keep", gov, "kept so a reinstall keeps your tier and exceptions; use --purge to delete"))
    backup = repo / render.BACKUP
    if backup.exists():
        acts.append(("keep", backup, "your settings.json from before Governor; kept"))
    return acts


def apply(repo, acts):
    repo = Path(repo).resolve()
    managed_p = repo / render.MANAGED
    managed = json.loads(managed_p.read_text(encoding="utf-8")) if managed_p.exists() else {}
    for action, path, _ in acts:
        if repo not in path.resolve().parents:
            raise RuntimeError(f"refused: {path} is outside the repository")
        if action == "edit":
            data = json.loads(path.read_text(encoding="utf-8-sig"))
            perms = data.get("permissions", {})
            for k in ("deny", "ask"):
                if k in perms:
                    perms[k] = [e for e in perms[k] if e not in set(managed.get(k, []))]
                    if not perms[k]:
                        del perms[k]
            if "permissions" in data and not data["permissions"]:
                del data["permissions"]
            hk = data.get("hooks", {})
            for event in list(hk):
                groups = [dict(g, hooks=[h for h in g.get("hooks", []) if not render.is_governor_hook(h)])
                          for g in hk[event]]
                hk[event] = [g for g in groups if g["hooks"]]
                if not hk[event]:
                    del hk[event]
            if "hooks" in data and not data["hooks"]:
                del data["hooks"]
            backup = repo / render.BACKUP
            try:
                original = json.loads(backup.read_text(encoding="utf-8-sig")) if backup.exists() else None
            except (json.JSONDecodeError, UnicodeDecodeError):
                original = None
            if original is not None and original == data:
                path.write_bytes(backup.read_bytes())   # nothing changed since: give back the user's exact bytes
                backup.unlink()                          # and the backup is now redundant
            elif data:
                path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
            else:
                path.unlink()   # Governor created it and nothing of yours is in it
        elif action == "delete":
            path.unlink(missing_ok=True)
        elif action == "delete_dir":
            shutil.rmtree(path, ignore_errors=True)
        elif action == "unblock":
            text = render.read_user_text(path)
            with open(path, "w", encoding="utf-8", newline="") as fh:
                fh.write(_without_block(text))
    shutil.rmtree(repo / ".claude" / "hooks" / "__pycache__", ignore_errors=True)   # left by older hook versions
    for d in (repo / ".claude" / "hooks", repo / ".claude" / "rules", repo / ".claude",
              repo / ".github" / "workflows", repo / ".github"):
        if d.is_dir() and not any(d.iterdir()):
            d.rmdir()


def main(argv=None):
    ap = argparse.ArgumentParser(allow_abbrev=False, description="Remove Governor from a repository (SPEC U1)")
    ap.add_argument("repo")
    ap.add_argument("--yes", action="store_true", help="really remove (otherwise only show the plan)")
    ap.add_argument("--purge", action="store_true", help="also delete governance.yaml")
    args = ap.parse_args(argv)
    acts = plan(args.repo, args.purge)
    if not any(a != "keep" for a, _, _ in acts):
        print("Governor is not installed here; nothing to remove.")
        return 0
    repo = Path(args.repo).resolve()
    for action, path, detail in acts:
        verb = {"edit": "edit", "delete": "delete", "delete_dir": "delete", "unblock": "edit", "keep": "keep"}[action]
        print(f"{verb:6} {path.relative_to(repo).as_posix()}: {detail}")
    if not args.yes:
        print("\nNothing was changed. To remove Governor, run this yourself in a terminal, adding --yes.")
        return 0
    apply(repo, acts)
    print("\nGovernor removed. Restart Claude Code so the hooks stop loading, then review `git diff`.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
