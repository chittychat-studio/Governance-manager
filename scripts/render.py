"""Render governance.yaml into agent config (SPEC R1-R6, X2, P4, P7).

Claude Code outputs: .claude/rules/governor.md, .claude/settings.json (merged, R5),
.claude/hooks/governor_*.py + governor_config.json, .claude/governor/COVERAGE.md (R6),
.claude/.governor-managed.json, and CLAUDE.md only when absent or Governor-owned.

Usage: python scripts/render.py <repo>
"""
import json
import shutil
import stat
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import governance  # noqa: E402
from packs import PackError, read_lock, resolve  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
TEMPLATES = ROOT / "templates" / "hooks"
HOOK_FILES = ["governor_common.py", "governor_pretool.py", "governor_posttool.py", "governor_stop.py"]
MD_HEADER = "<!-- Generated by Governor. Do not edit: change governance.yaml and re-run render (R4). -->"
PY_HEADER = "# Generated by Governor. Do not edit: change governance.yaml and re-run render (R4).\n"
MANAGED = ".claude/.governor-managed.json"
RULES_MD = ".claude/rules/governor.md"
COVERAGE_MD = ".claude/governor/COVERAGE.md"
BACKUP = ".claude/settings.json.governor-backup"
SECTIONS = ["## Enforced rules", "## Advisory rules", "## Disabled rules", "## Commands"]
HOOK_EVENTS = {
    "PreToolUse": ("Bash|Read|Edit|Write|MultiEdit|NotebookEdit|Grep|Glob|mcp__.*", "governor_pretool.py", 30),
    "PostToolUse": ("Bash|Edit|Write|MultiEdit|NotebookEdit", "governor_posttool.py", 30),
    "PostToolUseFailure": ("Bash", "governor_posttool.py", 30),
    "Stop": (None, "governor_stop.py", 900),
}


class RenderError(ValueError):
    """Refuse to render (P4 pin mismatch, unreadable settings)."""


def hook_command(script, hook_python):
    """Shell command for a hook. 'auto' tries python3, then python (Windows installs often lack python3)."""
    target = f'"$CLAUDE_PROJECT_DIR/.claude/hooks/{script}"'
    if hook_python == "auto":
        return f"p=python3; $p -c '' 2>/dev/null || p=python; exec \"$p\" {target}"
    return f"exec {hook_python} {target}"


def verify_pins(gov):
    """Installed pins must equal PACKS.lock; else refuse (P4)."""
    lock = read_lock()
    for agent, p in gov["packs"].items():
        for pin in p["pins"]:
            if lock.get(pin["id"]) != pin["sha256"]:
                raise RenderError(f"refused: pack {pin['id']} changed since governance.yaml was written (P4). "
                                  "Re-run scripts/governance.py to re-pin.")


def split_rules(gov, agent):
    """Return (rules, disabled {id: reason}) for one agent (X2)."""
    rules = [r for r in resolve(gov["packs"][agent]["pack_id"])[0] if agent in r["agents"]]
    disabled = {e["rule"]: e["reason"] for e in gov.get("exceptions", []) if e.get("kind") == "rule"}
    return rules, disabled


def hook_config(gov, rules, disabled):
    """Build governor_config.json from enabled rules' hook payloads (P6-P10)."""
    cfg = {"_comment": "Generated by Governor (R4). Do not edit.", "test_cmd": gov["intake"]["test_cmd"],
           "mcp_allow": gov.get("mcp_allow", []), "stop_max_blocks": 3,
           "bash_deny": [], "bash_ask": [], "path_deny": [], "path_deny_write": []}
    for r in rules:
        h = r.get("hook")
        if not h or r["id"] in disabled:
            continue
        for kind in ("bash_deny", "bash_ask"):
            cfg[kind] += [{"pattern": p, "rule": r["id"], "text": r["text"]} for p in h.get(kind, [])]
        if h.get("path_deny"):
            cfg["path_deny"].append({"globs": h["path_deny"], "allow": h.get("path_allow", []),
                                     "rule": r["id"], "text": r["text"]})
        if h.get("path_deny_write"):
            cfg["path_deny_write"].append({"globs": h["path_deny_write"], "rule": r["id"], "text": r["text"]})
        if h.get("mcp_allowlist"):
            cfg["mcp_allowlist_rule"] = r["id"]
        if h.get("secret_scan"):
            cfg["secret_scan_rule"] = r["id"]
        if h.get("stop_tests"):
            cfg["stop_tests_rule"] = r["id"]
        if h.get("repeat_fail"):
            cfg["repeat_fail"] = {"n": h["repeat_fail"], "rule": r["id"]}
    return cfg


def rules_markdown(gov, rules, disabled):
    """.claude/rules/governor.md: rule text only, no prose (R3, V1, V2, X2)."""
    tier = gov["tier"]
    lines = [MD_HEADER, f"# Governor rules (tier {tier['effective']})", ""]
    enforced = [r for r in rules if r["enforcement"] == "enforced" and r["id"] not in disabled]
    advisory = [r for r in rules if r["enforcement"] == "advisory" and r["id"] not in disabled]
    lines.append(SECTIONS[0])
    lines += [f"- {r['id']}: {r['text']}" for r in enforced] or ["- none"]
    lines += ["", SECTIONS[1]]
    lines += [f"- {r['id']}: {r['text']}" for r in advisory] or ["- none"]
    lines += ["", SECTIONS[2]]
    lines += [f"- {rid}: disabled: {reason}" for rid, reason in disabled.items()
              if rid in {r["id"] for r in rules}] or ["- none"]
    lines += ["", SECTIONS[3], f"- Tests: `{gov['intake']['test_cmd']}` must pass before you finish."]
    if tier["effective"] < tier["computed"]:
        lines.append(f"- Tier lowered from {tier['computed']} by exception; see governance.yaml.")
    return "\n".join(lines) + "\n"


def coverage_markdown(gov, per_agent):
    """Coverage table per agent: enforced vs advisory vs disabled (R6)."""
    out = [MD_HEADER, "# Governor coverage", "",
           f"Tier {gov['tier']['effective']} (computed {gov['tier']['computed']}, matched "
           f"{', '.join(gov['tier']['matched'])}). Packs are hash-pinned, not signed (P4a).", ""]
    for agent, (rules, disabled) in per_agent.items():
        enf = sum(1 for r in rules if r["enforcement"] == "enforced" and r["id"] not in disabled)
        adv = sum(1 for r in rules if r["enforcement"] == "advisory" and r["id"] not in disabled)
        dis = sum(1 for r in rules if r["id"] in disabled)
        out += [f"## {agent}", "", f"Enforced: {enf} · Advisory: {adv} · Disabled: {dis}", "",
                "| Rule | Status | Mechanism |", "|---|---|---|"]
        for r in rules:
            status = "disabled" if r["id"] in disabled else r["enforcement"]
            out.append(f"| {r['id']} | {status} | {' + '.join(r['mechanism'])} |")
        out.append("")
    out.append("Enforced means a hook or permission rule acts on the tool call. It is not an OS-level "
               "sandbox, and this is not a compliance certificate.")
    return "\n".join(out) + "\n"


def merge_settings(repo, deny, ask, hooks, managed_old):
    """Merge into .claude/settings.json: back up once, drop previous Governor entries, add current (R5)."""
    path = repo / ".claude" / "settings.json"
    if path.exists():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise RenderError(f"refused: existing .claude/settings.json is not valid JSON ({exc}) (R5)")
        backup = repo / BACKUP
        if not backup.exists():
            shutil.copy2(path, backup)
    else:
        data = {}
    perms = data.setdefault("permissions", {})
    for key, new in (("deny", deny), ("ask", ask)):
        old_owned = set(managed_old.get(key, []))
        kept = [e for e in perms.get(key, []) if e not in old_owned]
        perms[key] = kept + [e for e in new if e not in kept]
        if not perms[key]:
            del perms[key]
    hk = data.setdefault("hooks", {})
    for event in list(hk):
        groups = []
        for g in hk[event]:
            inner = [h for h in g.get("hooks", []) if "/.claude/hooks/governor_" not in h.get("command", "")]
            if inner:
                groups.append(dict(g, hooks=inner))
        hk[event] = groups
        if not groups:
            del hk[event]
    for event, group in hooks.items():
        hk.setdefault(event, []).append(group)
    if not perms:
        del data["permissions"]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")


def render(repo):
    """Render all Claude Code outputs for <repo> from governance.yaml (R1-R6). Returns written paths."""
    repo = Path(repo).resolve()
    gov = governance.read(repo)
    if gov is None:
        raise RenderError("refused: no governance.yaml (R1)")
    verify_pins(gov)
    if "claude-code" not in gov["packs"]:
        return []
    rules, disabled = split_rules(gov, "claude-code")
    enabled = [r for r in rules if r["id"] not in disabled]
    deny = [d for r in enabled for d in r.get("deny", [])]
    ask = [a for r in enabled for a in r.get("ask", [])]
    hooks = {}
    for event, (matcher, script, timeout) in HOOK_EVENTS.items():
        group = {"hooks": [{"type": "command", "command": hook_command(script, gov.get("hook_python", "auto")),
                            "timeout": timeout}]}
        if matcher:
            group = {"matcher": matcher, **group}
        hooks[event] = group

    managed_path = repo / MANAGED
    managed_old = json.loads(managed_path.read_text(encoding="utf-8")) if managed_path.exists() else {}
    written = []

    hook_dir = repo / ".claude" / "hooks"
    hook_dir.mkdir(parents=True, exist_ok=True)
    for name in HOOK_FILES:
        dst = hook_dir / name
        dst.write_text(PY_HEADER + (TEMPLATES / name).read_text(encoding="utf-8"), encoding="utf-8")
        dst.chmod(dst.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
        written.append(dst)
    cfg_path = hook_dir / "governor_config.json"
    cfg_path.write_text(json.dumps(hook_config(gov, rules, disabled), indent=2) + "\n", encoding="utf-8")
    written.append(cfg_path)

    rules_path = repo / RULES_MD
    rules_path.parent.mkdir(parents=True, exist_ok=True)
    rules_path.write_text(rules_markdown(gov, rules, disabled), encoding="utf-8")
    written.append(rules_path)

    cov = repo / COVERAGE_MD
    cov.parent.mkdir(parents=True, exist_ok=True)
    cov.write_text(coverage_markdown(gov, {"claude-code": (rules, disabled)}), encoding="utf-8")
    written.append(cov)

    claude_md = repo / "CLAUDE.md"
    owns_claude_md = not claude_md.exists() or claude_md.read_text(encoding="utf-8").startswith(MD_HEADER)
    if owns_claude_md:
        claude_md.write_text(f"{MD_HEADER}\n# Project instructions\n\n- Governance rules load from "
                             f"`{RULES_MD}`.\n- Run `{gov['intake']['test_cmd']}` before you finish.\n",
                             encoding="utf-8")
        written.append(claude_md)

    merge_settings(repo, deny, ask, hooks, managed_old)
    written.append(repo / ".claude" / "settings.json")

    managed = {"_comment": "Generated by Governor (R4, R5). Lists what Governor owns.",
               "deny": deny, "ask": ask, "hook_events": sorted(hooks),
               "files": sorted(p.relative_to(repo).as_posix() for p in written if p.name != "settings.json"),
               "claude_md_owned": owns_claude_md}
    managed_path.write_text(json.dumps(managed, indent=2) + "\n", encoding="utf-8")
    written.append(managed_path)
    return written


def main(argv=None):
    """CLI (R1-R6)."""
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        written = render(argv[0])
    except (RenderError, PackError) as exc:
        print(str(exc), file=sys.stderr)
        return 4
    for p in written:
        print(p)
    print("status: generated (run scripts/lint.py next; generated != linted != verified, Q5)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
