class RenderError(ValueError):
    """Refuse to render (P4 pin mismatch, unreadable settings)."""


CANNOT_FAIL = re.compile(r"(?i)^(true|:|exit\s+0|echo\b[^;&|]*|rem\b.*|#.*)$|(\|\||;)\s*(true|:|exit\s+0)\s*$")


def no_tests(gov):
    """True when the intake records that the repo has no test suite yet (I1c)."""
    return str(gov["intake"].get("test_cmd", "")).strip().lower() == "none"


def test_cmd_problem(gov):
    """I1b: why test_cmd would be refused, or None. The Stop hook runs it with a shell and no PreToolUse check,
    so it must pass the same rules an agent command would under the Claude Code pack."""
    import importlib.util
    cmd = str(gov["intake"].get("test_cmd", ""))
    if no_tests(gov):
        return None
    if "\n" in cmd or "\r" in cmd:
        return "refused: test command contains a line break (I1b)"
    if CANNOT_FAIL.search(cmd.strip()):
        return (f"refused: test command `{cmd[:80]}` cannot fail, so the Stop-hook test gate would always pass "
                "(I1b). Give the command that runs the tests, or `none` if there are none yet (I1c).")
    sys.path.insert(0, str(TEMPLATES))
    spec = importlib.util.spec_from_file_location("governor_pretool_check", TEMPLATES / "governor_pretool.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    if "claude-code" not in gov["packs"]:
        return None  # no Stop hook is rendered, so Governor never runs test_cmd
    rules, disabled = split_rules(gov, "claude-code")
    cfg = hook_config(gov, rules, disabled)
    cfg.pop("repeat_fail", None)
    cfg.pop("allow_if_clean", None)   # I1b: no session baseline, so nothing is written to disk
    event = {"tool_name": "Bash", "tool_input": {"command": cmd}, "session_id": "governor-test-cmd-check"}
    decision, rule, _ = mod.decide(event, cfg)
    if decision in ("deny", "ask"):
        return (f"refused: test command `{cmd[:80]}` would be {'blocked' if decision == 'deny' else 'held for approval'}"
                f" by rule {rule}. The Stop hook runs it without that check, so it must be a plain test command (I1b).")
    return None


def hook_handler(script, hook_python, timeout):
    """Exec-form hook: no shell, so it runs the same under Git Bash or PowerShell on Windows.
    Claude Code expands ${CLAUDE_PROJECT_DIR} itself (docs: code.claude.com/docs/en/hooks)."""
    py = default_python() if hook_python in (None, "", "auto") else hook_python
    return {"type": "command", "command": py,   # -B: no .pyc files in .claude/hooks/ to end up in commits
            "args": ["-B", f"${{CLAUDE_PROJECT_DIR}}/.claude/hooks/{script}"], "timeout": timeout}


def is_governor_hook(h):
    """True for a hook handler Governor rendered (either the old shell form or exec form)."""
    text = " ".join([h.get("command", "")] + [str(a) for a in h.get("args", [])])
    return "/.claude/hooks/governor_" in text


def verify_pins(gov):
    """Installed pins must equal PACKS.lock; else refuse (P4)."""
    lock = read_lock()
    for agent, p in gov["packs"].items():
        for pin in p["pins"]:
            if lock.get(pin["id"]) != pin["sha256"]:
                raise RenderError(f"refused: pack {pin['id']} changed since governance.yaml was written (P4). "
                                  "Re-run scripts/governance.py to re-pin.")


def split_rules(gov, agent):
    """Return (rules, disabled {id: reason}) for one agent (X2).

    Codex output is AGENTS.md only (E7): nothing enforces it, so every rule is advisory there (R6).
    """
    rules = [r for r in resolve(gov["packs"][agent]["pack_id"])[0] if agent in r["agents"]]
    if agent == "codex":
        rules = [dict(r, enforcement="advisory", mechanism=["instruction"]) for r in rules]
    disabled = {e["rule"]: e["reason"] for e in gov.get("exceptions", []) if e.get("kind") == "rule"}
    return rules, disabled


def hook_config(gov, rules, disabled):
    """Build governor_config.json from enabled rules' hook payloads (P6-P10)."""
    cfg = {"_comment": "Generated by Governor (R4). Do not edit.", "test_cmd": "" if no_tests(gov) else gov["intake"]["test_cmd"],
           "mcp_allow": gov.get("mcp_allow", []), "stop_max_blocks": 3,
           "bash_deny": [], "bash_ask": [], "bash_allow": {}, "path_deny": [], "path_deny_write": [],
           "plain": {r["id"]: {"plain": r["plain"], "you_can": r["you_can"]} for r in rules
                     if r.get("plain") and r["id"] not in disabled}}
    for r in rules:
        h = r.get("hook")
        if not h or r["id"] in disabled:
            continue
        for kind in ("bash_deny", "bash_ask"):
            cfg[kind] += [{"pattern": p, "rule": r["id"], "text": r["text"]} for p in h.get(kind, [])]
        if h.get("bash_allow"):
            cfg["bash_allow"][r["id"]] = list(h["bash_allow"])
        if h.get("allow_if_clean"):
            cfg.setdefault("allow_if_clean", {})[r["id"]] = list(h["allow_if_clean"])
        if h.get("guard"):
            cfg["guard"] = {"rule": r["id"], "text": r["text"]}
        if h.get("path_deny"):
            cfg["path_deny"].append({"globs": h["path_deny"], "allow": h.get("path_allow", []),
                                     "rule": r["id"], "text": r["text"]})
        if h.get("path_deny_write"):
            cfg["path_deny_write"].append({"globs": h["path_deny_write"], "rule": r["id"], "text": r["text"]})
        if h.get("monitor_ws_ask"):
            cfg["monitor_ws_rule"] = r["id"]
        if h.get("mcp_allowlist"):
            cfg["mcp_allowlist_rule"] = r["id"]
        if h.get("secret_scan"):
            cfg["secret_scan_rule"] = r["id"]
        if h.get("stop_tests"):
            cfg["stop_tests_rule"] = r["id"]
        if h.get("repeat_fail"):
            cfg["repeat_fail"] = {"n": h["repeat_fail"], "rule": r["id"]}
    if gov.get("docs") and cfg.get("guard"):   # PD6: always-loaded docs are checked on every write
        import lint
        d = gov["docs"]["dir"]
        cfg["docs_guard"] = {"rule": cfg["guard"]["rule"], "dir": d, "files": [f"{d}/rules.md", f"{d}/memory.md"],
                             "patterns": list(lint.GUARDRAIL_OFF)}
    return cfg


def claude_md_body(gov):
    """Governor's block in CLAUDE.md: a pointer to the rules file and the test command (R3), plus the project-docs
    index when /governor:docs has run (PD5)."""
    return (f"# Project instructions (Governor)\n\n- Governance rules load from `{RULES_MD}`.\n"
            f"- {_tests_line(gov)}\n") + docs_index(gov, imports=True)


DESIGN_RULE = ".claude/rules/governor-design.md"
