"""Install the Governor CI gate into a repo (SPEC D3, D4).

Vendors the deterministic runtime into <repo>/.governor/ (scripts, packs, tiers, schema, hook
templates) and writes .github/workflows/governor.yml, so CI needs no access to Governor's own
repo and makes no model calls.

Usage: python scripts/ci.py install <repo>
"""
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import governance  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
EXCLUDED_SCRIPTS = {"verify.py", "c1_budget.py"}  # spend credits (E4); never in client CI (D4)
WORKFLOW = ".github/workflows/governor.yml"


def install(repo):
    """Vendor the runtime and write the workflow (D3). Returns written paths."""
    repo = Path(repo).resolve()
    dst = repo / ".governor"
    if dst.exists():
        shutil.rmtree(dst)
    (dst / "scripts").mkdir(parents=True)
    for src in sorted((ROOT / "scripts").glob("*.py")):
        if src.name not in EXCLUDED_SCRIPTS:
            shutil.copy2(src, dst / "scripts" / src.name)
    shutil.copytree(ROOT / "packs", dst / "packs")
    shutil.copytree(ROOT / "templates" / "hooks", dst / "templates" / "hooks")
    for name in ("tiers.yaml", "intake.schema.json"):
        shutil.copy2(ROOT / name, dst / name)
    (dst / "VERSION").write_text(governance.GOVERNOR_VERSION + "\n", encoding="utf-8")
    (dst / "README.md").write_text("<!-- Generated by Governor (R4). -->\nVendored Governor runtime used by "
                                   f"`{WORKFLOW}`. Do not edit; re-run `scripts/ci.py install`.\n", encoding="utf-8")
    wf = repo / WORKFLOW
    wf.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(ROOT / "templates" / "github" / "governor.yml", wf)
    return [dst, wf]


def main(argv=None):
    """CLI (D3)."""
    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 2 or argv[0] != "install":
        print(__doc__, file=sys.stderr)
        return 2
    for p in install(argv[1]):
        print(p)
    return 0


if __name__ == "__main__":
    sys.exit(main())
